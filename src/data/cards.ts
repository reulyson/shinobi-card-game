/** IDs de todos os Jutsus Exclusivos (não podem entrar no baralho). */
export const SIGNATURE_JUTSU_IDS: ReadonlySet<string> = new Set(
  NINJA_CARDS.map((n) => n.signatureJutsuId).filter((id) => id !== '')
);

/** Ninja dono de um Jutsu Exclusivo, se houver. */
export function getSignatureOwner(jutsuId: string): NinjaCardDef | undefined {
  if (!jutsuId) return undefined;
  return NINJA_CARDS.find((n) => n.signatureJutsuId === jutsuId);
}

/** Pode ir para o baralho? (Tokens e Jutsus Exclusivos só são criados durante a partida.) */
export function isDeckableCard(card: CardDef): boolean {
  if (card.kind === 'token') return false;
  if (card.kind === 'jutsu' && SIGNATURE_JUTSU_IDS.has(card.id)) return false;
  if (NINJA_CREATED_ONLY_IDS.has(card.id)) return false;
  return true;
}

/** Motivo para uma carta não poder ir ao baralho (ou null). */
export function getNotDeckableReason(card: CardDef): string | null {
  if (card.kind === 'token') return 'Token: criado durante a partida, não entra no baralho.';
  if (NINJA_CREATED_ONLY_IDS.has(card.id)) return 'Criado por um Ninja durante a partida: não entra no baralho.';
  if (card.kind === 'jutsu' && SIGNATURE_JUTSU_IDS.has(card.id)) {
    const owner = getSignatureOwner(card.id);
    return `Jutsu Exclusivo${owner ? ` de ${owner.name}` : ''}: é criado na mão quando o Ninja entra em campo.`;
  }
  return null;
}

/** Valida um baralho pelas regras de construção. */
export function validateDeck(cardIds: readonly string[]): { ok: boolean; errors: string[] } {
  const errors: string[] = [];
  if (cardIds.length !== 24) errors.push(`O baralho precisa ter exatamente 24 cartas (tem ${cardIds.length}).`);
  const counts: Record<string, number> = {};
  for (const id of cardIds) counts[id] = (counts[id] || 0) + 1;
  let ninjas = 0;
  for (const [id, n] of Object.entries(counts)) {
    const card = getCardById(id);
    if (!card) {
      errors.push(`Carta desconhecida: ${id}.`);
      continue;
    }
    const reason = getNotDeckableReason(card);
    if (reason) errors.push(`${card.name} — ${reason}`);
    if (card.kind === 'ninja') {
      ninjas += 1;
      if (n > 2) errors.push(`${card.name}: máximo de 2 cópias por Ninja.`);
    } else if (n > 3) {
      errors.push(`${card.name}: máximo de 3 cópias.`);
    }
  }
  if (ninjas > 3) errors.push('Máximo de 3 Ninjas distintos por baralho.');
  return { ok: errors.length === 0, errors };
}

/**
 * Carta que uma cópia repetida de um Ninja vira (Ninja Único):
 * o Token Exclusivo, se o Ninja tiver um; senão, o Jutsu Exclusivo; e, para Ninja sem Exclusivo,
 * o Jutsu geral que combina com ele (generalJutsuId).
 */
export function getNinjaDuplicateCardId(ninja: NinjaCardDef): string {
  if (ninja.exclusiveTokenId && getCardById(ninja.exclusiveTokenId)) return ninja.exclusiveTokenId;
  if (ninja.signatureJutsuId) return ninja.signatureJutsuId;
  return ninja.generalJutsuId ?? '';
}

/** Patente máxima do Ninja (1 a 3; padrão 3). */
export function getNinjaMaxRank(ninja: NinjaCardDef): 1 | 2 | 3 {
  return ninja.maxRank ?? 3;
}
