function pv(
  power: number,
  vitality: number,
  basePower: number,
  baseVitality: number,
  dying?: boolean
): FieldCardPreview {
  return {
    power,
    vitality,
    basePower,
    baseVitality,
    dying: dying ?? vitality <= 0,
  };
}

